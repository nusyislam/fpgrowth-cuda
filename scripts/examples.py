#!/usr/bin/env python3
"""Decoded example patterns for the report -> results/examples.txt.

1. Mushroom, odor -> class: the transactions are projected onto the odor and
   class items, ./fpgrowth mines the projection at min_support 1, and the
   confidence of every rule {odor=x} -> {class=y} is support(x, y) / support(x).
2. Online Retail, the Regency teacup itemsets at 1% support, and the
   confidence of {GREEN, PINK} -> {ROSES}.

Needs ./fpgrowth and data/processed/ (make, make data).
"""
import csv
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROCESSED = ROOT / "data" / "processed"
OUT = ROOT / "results" / "examples.txt"
BINARY = ROOT / "fpgrowth"


def read_map(name):
    with (PROCESSED / f"{name}.map.tsv").open(newline="") as f:
        r = csv.reader(f, delimiter="\t")
        next(r)
        return {int(i): n for i, n in r}


def mine(dat, support):
    """{frozenset(items): support} from one ./fpgrowth run."""
    out = subprocess.run([str(BINARY), str(dat), str(support)],
                         capture_output=True, text=True, check=True).stdout
    sets = {}
    for line in out.splitlines():
        head, _, sup = line.rpartition(" (")
        sets[frozenset(int(x) for x in head.split())] = int(sup.rstrip(")"))
    return sets


def mushroom(lines):
    names = read_map("mushroom")
    keep = {i for i, n in names.items() if n.startswith(("odor=", "class="))}
    proj = ROOT / "results" / ".mushroom_odor_class.dat"
    txs = [[int(x) for x in l.split()] for l in (PROCESSED / "mushroom.dat").read_text().splitlines()]
    proj.write_text("".join(" ".join(str(i) for i in t if i in keep) + "\n" for t in txs))
    try:
        sets = mine(proj, 1)
    finally:
        proj.unlink()
    n = len(txs)
    odors = sorted((i for i in keep if names[i].startswith("odor=")), key=lambda i: -sets[frozenset([i])])
    classes = sorted(i for i in keep if names[i].startswith("class="))
    lines.append(f"Mushroom ({n} transactions): rules {{odor}} -> {{class}}, mined from the odor/class projection")
    lines.append(f"{'odor':<16}{'support':>8}  " + "  ".join(f"{names[c]:>24}" for c in classes))
    for o in odors:
        so = sets[frozenset([o])]
        cells = []
        for c in classes:
            s = sets.get(frozenset([o, c]), 0)
            cells.append(f"{s:>6} (conf {s / so:.3f})".rjust(24))
        lines.append(f"{names[o]:<16}{so:>8}  " + "  ".join(cells))
    lines.append("")


def retail(lines):
    names = read_map("online_retail")
    support = 0.01
    sets = mine(PROCESSED / "online_retail.dat", support)
    n = sum(1 for _ in (PROCESSED / "online_retail.dat").open())
    tea = {i for i, nm in names.items() if "REGENCY TEACUP AND SAUCER" in nm}
    lines.append(f"Online Retail ({n} transactions), min_support {support}: itemsets of Regency teacups only")
    rows = sorted((s for s in sets if s <= tea), key=lambda s: (-sets[s], len(s)))
    for s in rows:
        lines.append(f"{sets[s]:>6}  " + ", ".join(names[i] for i in sorted(s)))
    by = {nm.split()[1]: i for i, nm in names.items() if i in tea}  # GREEN / PINK / ROSES
    lhs = frozenset([by["GREEN"], by["PINK"]])
    full = lhs | {by["ROSES"]}
    lines.append(f"rule {{GREEN, PINK}} -> {{ROSES}}: support {sets[full]}, "
                 f"confidence {sets[full]} / {sets[lhs]} = {sets[full] / sets[lhs]:.3f}, "
                 f"P(ROSES) = {sets[frozenset([by['ROSES']])]} / {n} = {sets[frozenset([by['ROSES']])] / n:.3f}")
    lines.append("")


def main():
    lines = ["# Generated by scripts/examples.py", ""]
    mushroom(lines)
    retail(lines)
    OUT.write_text("\n".join(lines))
    print(OUT.read_text())


if __name__ == "__main__":
    main()
