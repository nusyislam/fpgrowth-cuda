#!/usr/bin/env python3
"""Write results/tables.md: markdown tables for the report.

  1. dataset statistics          (results/dataset_stats.csv)
  2. support-sweep summary       (results/bench.csv; "ok" rows, plus where it stopped)
  3. runtime vs mlxtend          (results/vs_mlxtend.csv)

Usage: make_tables.py
"""
import csv

from benchlib import DATASETS, RESULTS

LABEL = {"chess": "Chess", "mushroom": "Mushroom", "connect4": "Connect-4",
         "online_retail": "Online Retail"}
STOP = {"over_time_budget": "run > 60 s", "timeout": "killed at 120 s",
        "memory_limit": "hit 4 GB limit"}


def read(name):
    with (RESULTS / name).open(newline="") as f:
        return list(csv.DictReader(f))


def pct(x):
    v = 100 * float(x)
    return f"{v:.2g}%" if v < 1 else f"{v:.3g}%"


def secs(x):
    x = float(x)
    if x < 1:
        return f"{x * 1000:.3g} ms"
    return f"{x:.3g} s"


def count(x):
    x = float(x)
    for div, suf in ((1e9, "G"), (1e6, "M"), (1e3, "k")):
        if x >= div:
            return f"{x / div:.3g}{suf}"
    return f"{x:.0f}"


def size(b):
    b = float(b)
    for unit in ("B", "KB", "MB", "GB"):
        if b < 1024 or unit == "GB":
            return f"{b:.0f} {unit}" if unit == "B" else f"{b:.1f} {unit}"
        b /= 1024


def table(header, rows, align):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(":---" if a == "l" else "---:" for a in align) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def dataset_stats():
    rows = {r["dataset"]: r for r in read("dataset_stats.csv")}
    body = [[LABEL[n], f"{int(r['transactions']):,}", f"{int(r['distinct_items']):,}",
             f"{float(r['avg_len']):.2f}", r["min_len"], r["max_len"],
             f"{float(r['density']):.4f}", size(r["file_size_bytes"])]
            for n in DATASETS if (r := rows.get(n))]
    return table(["Dataset", "Transactions", "Distinct items", "Avg len", "Min len",
                  "Max len", "Density", "File size"], body, "lrrrrrrr")


def sweep_summary():
    bench = read("bench.csv")
    body = []
    for n in DATASETS:
        rows = [r for r in bench if r["dataset"] == n]
        ok = sorted((r for r in rows if r["status"] == "ok"), key=lambda r: -float(r["min_support"]))
        stop = [r for r in rows if r["status"] != "ok"]
        if not ok:
            continue
        hi, lo = ok[0], ok[-1]
        ratio_hi = float(hi["tree_nodes"]) / float(hi["filtered_occurrences"])
        ratio_lo = float(lo["tree_nodes"]) / float(lo["filtered_occurrences"])
        body.append([
            LABEL[n], len(ok),
            f"{pct(hi['min_support'])} – {pct(lo['min_support'])}",
            f"{count(hi['itemsets'])} – {count(lo['itemsets'])}",
            f"{secs(hi['total_s'])} – {secs(lo['total_s'])}",
            f"{float(hi['peak_rss_kb']) / 1024:.1f} – {float(lo['peak_rss_kb']) / 1024:.1f} MB",
            f"{ratio_hi:.4f} – {ratio_lo:.4f}",
            (f"{pct(stop[0]['min_support'])} ({STOP.get(stop[0]['status'], stop[0]['status'])})"
             if stop else f"budget not reached (lowest level {secs(lo['total_s'])})"),
        ])
    return table(["Dataset", "Levels", "Min support", "Frequent itemsets", "Total time",
                  "Peak RSS", "Tree nodes / occurrences", "Stopped at"], body, "lrrrrrrl")


def vs_mlxtend():
    body = []
    for r in read("vs_mlxtend.csv"):
        ok = r["status"] == "ok"
        body.append([LABEL[r["dataset"]], pct(r["min_support"]), f"{int(r['itemsets']):,}",
                     secs(r["binary_total_s"]), secs(r["mlxtend_s"]) if ok else "skipped",
                     f"{float(r['speedup']):.1f}×" if ok else "–"])
    return table(["Dataset", "Min support", "Itemsets", "This implementation (total)",
                  "mlxtend (fpgrowth call)", "Speedup"], body, "lrrrrr")


def main():
    md = [
        "# Benchmark tables",
        "",
        "Generated by `scripts/make_tables.py` from the CSVs in `results/`. "
        "Machine: see `results/machine.txt`.",
        "",
        "## Datasets",
        "",
        "Density = average transaction length / distinct items.",
        "",
        dataset_stats(),
        "",
        "## Support sweep summary",
        "",
        "Ranges go from the highest to the lowest completed support level. Times and "
        "memory are medians of 5 runs with `--unsorted` output to `/dev/null` "
        "(total = read + build + mine, where mining includes formatting the itemsets). "
        "Tree nodes / occurrences is the size of the initial FP-tree relative to the "
        "number of frequent-item occurrences inserted into it (lower = more prefix "
        "sharing). \"Stopped at\" is the first level that exceeded the budget.",
        "",
        sweep_summary(),
        "",
        "## Runtime vs mlxtend",
        "",
        "Medians of 3 runs. This implementation's time includes reading the .dat file, "
        "building the tree, mining and formatting every itemset; mlxtend's time is only "
        "the `fpgrowth()` call on an already one-hot-encoded DataFrame. All 13 settings "
        "produce identical itemsets (`tests/compare_mlxtend.py`). This implementation is "
        "single-threaded; mlxtend averaged ~1.25 CPU-seconds per wall-second, and forcing "
        "single-threaded BLAS (`OMP_NUM_THREADS=1` etc.) gave similar times, so the gap is "
        "not a threading effect.",
        "",
        vs_mlxtend(),
        "",
    ]
    out = RESULTS / "tables.md"
    out.write_text("\n".join(md))
    print(f"wrote {out.relative_to(RESULTS.parent)}")


if __name__ == "__main__":
    main()
